/* npm run lab:report — writes docs/RESOURCE_VISUAL_LAB_REPORT.md from what is ACTUALLY stored.
   Nothing is estimated: a number appears only if a stored record produced it. */
import { writeFileSync } from 'fs';
import path from 'path';
import { gridSimilarity } from '../../lib/devlab/metrics';
import { readReviews } from '../../lib/devlab/store';
import type { GenRecord } from '../../lib/devlab/types';
import { gridsOf, loadAll, refuseOnVercel } from './common';

refuseOnVercel();
const { dataset, results } = loadAll();
const reviews = readReviews();
const all = dataset.resources.map(r => ({ r, g: results.get(r.id) }));
const qwen = all.filter(x => x.g?.source === 'qwen');
const ok = qwen.filter(x => x.g!.status === 'ok');
const failed = qwen.filter(x => x.g!.status === 'failed');
const fixtures = all.filter(x => x.g?.source === 'fixture');
const notRun = all.filter(x => !x.g || x.g.source === 'fixture');

const med = (a: number[]) => { if (!a.length) return NaN; const s = [...a].sort((x, y) => x - y); return s[Math.floor(s.length / 2)]; };
const f = (n: number, d = 2) => (Number.isFinite(n) ? n.toFixed(d) : 'n/a');
const stat = (label: string, a: number[], d = 2) => `| ${label} | ${a.length ? f(Math.min(...a), d) : 'n/a'} | ${f(med(a), d)} | ${a.length ? f(Math.max(...a), d) : 'n/a'} |`;
const m = (pick: (g: GenRecord) => number | undefined) => ok.map(x => pick(x.g!)).filter((v): v is number => typeof v === 'number');

const L: string[] = [];
L.push('# Resource Visual Lab — success / failure report', '', `Generated ${new Date().toISOString()} by \`npm run lab:report\` from \`dev-data/visual-lab/results\`. Development prototype only; not part of the production catalogue.`, '');
L.push('## 1. Outcome', '');
if (qwen.length === 0) {
  L.push('> **No model generation has been run.** Zero of 100 resources have a Qwen-generated visual. Run `npm run lab:check` then `npm run lab:generate`. Nothing below is a result.', '');
}
L.push('| | count |', '|---|---|', `| Resources in dataset | ${dataset.resources.length} |`, `| Generated by Qwen and passing validation + quality gate | ${ok.length} |`, `| Attempted by Qwen and FAILED (recorded, no placeholder drawn) | ${failed.length} |`, `| Not attempted | ${all.filter(x => !x.g).length} |`, `| Hand-authored fixtures (excluded from every count above) | ${fixtures.length} |`, '');
if (qwen.length) L.push(`Model: ${[...new Set(qwen.map(x => x.g!.model))].join(', ')}. Attempts per resource: median ${f(med(qwen.map(x => x.g!.attempts.length)), 0)}; model time per attempt: median ${f(med(qwen.flatMap(x => x.g!.attempts.map(a => a.ms))) / 1000, 1)} s.`, '');

L.push('## 2. By category', '', '| Category | ok | failed | not attempted |', '|---|---|---|---|');
for (const c of dataset.categories) {
  const rows = all.filter(x => x.r.category === c.id);
  L.push(`| ${c.id} ${c.name} | ${rows.filter(x => x.g?.source === 'qwen' && x.g.status === 'ok').length} | ${rows.filter(x => x.g?.source === 'qwen' && x.g.status === 'failed').length} | ${rows.filter(x => !x.g || x.g.source === 'fixture').length} |`);
}
L.push('');

L.push('## 3. Failures (exact reasons)', '');
if (!failed.length) L.push('_None recorded._', '');
else {
  L.push('| id | name | kind | attempts | reason |', '|---|---|---|---|---|');
  for (const x of failed) L.push(`| ${x.r.id} | ${x.r.name} | ${x.g!.failure?.kind} | ${x.g!.attempts.length} | ${(x.g!.failure?.message ?? '').replace(/\|/g, '/').slice(0, 160)} |`);
  L.push('');
  const byKind = new Map<string, number>();
  for (const x of failed) byKind.set(x.g!.failure?.kind ?? '?', (byKind.get(x.g!.failure?.kind ?? '?') ?? 0) + 1);
  L.push(`By kind: ${[...byKind].map(([k, v]) => `${k}=${v}`).join(', ')}`, '');
}

L.push('## 4. Automated measurements (measured by code — not judgements)', '');
if (!ok.length) L.push('_No successful generations to measure._', '');
else {
  L.push(`Over ${ok.length} successful Qwen generations. Columns: min / median / max.`, '', '| measurement | min | median | max |', '|---|---|---|---|');
  L.push(stat('geometric detail: paths', m(g => g.metrics?.detail.paths), 0), stat('geometric detail: bezier/line segments', m(g => g.metrics?.detail.segments), 0), stat('geometric detail: parts', m(g => g.metrics?.detail.parts), 0), stat('geometric detail: component kinds', m(g => g.metrics?.detail.componentKinds), 0), stat('geometric detail: depth layers', m(g => g.metrics?.detail.layers), 0));
  L.push(stat('composition: fill (share of 16×16 cells inked)', m(g => g.metrics?.composition.fill), 3), stat('composition: centre offset (plate units)', m(g => g.metrics?.composition.centreOffset), 1), stat('composition: smallest margin (plate units)', m(g => g.metrics?.composition.margin), 1));
  L.push(stat('style proxy distance to hand art (0 = same statistics)', m(g => g.metrics?.style.distance), 3), stat('runtime: spec→markup compile (ms, Node)', m(g => g.metrics?.performance.compileMs), 2), stat('rendering: markup size (bytes)', m(g => g.metrics?.rendering.markupBytes), 0));
  const bad = ok.filter(x => !x.g!.metrics!.rendering.finite || !x.g!.metrics!.rendering.markupSafe);
  L.push('', `Rendering correctness: ${ok.length - bad.length} / ${ok.length} have finite coordinates and markup free of scripts/links. Specs with validation warnings (clamped values): ${ok.filter(x => (x.g!.validationWarnings?.length ?? 0) > 0).length}.`, '');
  const grids = gridsOf(ok.map(x => x.g!));
  const pairs: { a: string; b: string; s: number }[] = [];
  for (let i = 0; i < grids.length; i++) for (let j = i + 1; j < grids.length; j++) pairs.push({ a: grids[i].id, b: grids[j].id, s: gridSimilarity(grids[i].grid, grids[j].grid) });
  pairs.sort((p, q) => q.s - p.s);
  L.push(`Uniqueness (Jaccard overlap of 16×16 silhouette grids, ${pairs.length} pairs): median ${f(med(pairs.map(p => p.s)), 3)}; most similar pairs:`, '', '| a | b | overlap |', '|---|---|---|');
  for (const p of pairs.slice(0, 8)) L.push(`| ${p.a} | ${p.b} | ${f(p.s, 3)} |`);
  L.push('', 'Not measured here: per-frame cost in the browser (3D wireframe + particles). The gallery shows live `buildModel` time per plate; record it by hand if you need it.', '');
}

L.push('## 5. Manual review (human judgement — recorded in the gallery)', '');
const rv = Object.entries(reviews);
const dec = (d: string) => rv.filter(([, v]) => v.decision === d).length;
L.push(`Reviewed: ${rv.length} of ${dataset.resources.length}. Approved ${dec('approved')}, rejected ${dec('rejected')}, pending ${dec('pending')}.`, '');
const dims = ['recognizability', 'style', 'detail', 'uniqueness', 'composition'] as const;
if (rv.some(([, v]) => v.scores)) {
  L.push('| dimension | n scored | mean (1–5) |', '|---|---|---|');
  for (const d of dims) { const a = rv.map(([, v]) => v.scores?.[d]).filter((v): v is number => typeof v === 'number'); L.push(`| ${d} | ${a.length} | ${a.length ? f(a.reduce((x, y) => x + y, 0) / a.length) : 'n/a'} |`); }
  L.push('');
} else L.push('_No manual scores recorded yet. Recognisability in particular can only be judged by a person looking at the plate._', '');

L.push('## 6. Definition of done — honest status', '');
const chk = (b: boolean) => (b ? 'yes' : 'NO');
L.push('| criterion | met? |', '|---|---|', `| 100 distinct resources defined, none in the catalogue | yes (see tests) |`, `| Qwen produced a spec for all 100 | ${chk(ok.length + failed.length === 100)} (${ok.length + failed.length}/100 attempted) |`, `| All 100 render without failure | ${chk(ok.length === 100)} (${ok.length}/100) |`, `| Every failure recorded with a reason | ${chk(failed.every(x => !!x.g!.failure))} |`, `| Manual recognisability review complete | ${chk(rv.length === 100)} (${rv.length}/100) |`, '');
writeFileSync(path.join(process.cwd(), 'docs', 'RESOURCE_VISUAL_LAB_REPORT.md'), L.join('\n') + '\n');
console.log(`wrote docs/RESOURCE_VISUAL_LAB_REPORT.md — ${ok.length} ok, ${failed.length} failed, ${notRun.length} not attempted (${fixtures.length} fixtures excluded)`);
