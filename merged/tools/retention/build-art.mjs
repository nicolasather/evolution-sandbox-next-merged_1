// Bundles the committed, hand-authored retention SVG sources into lazy-loadable TypeScript modules.
// The SVG files under data/retention/characters and data/retention/cosmetics are the source of truth.
// Run: node tools/retention/build-art.mjs   (validate.mjs checks the sources; this only packs them)
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const groups = {
  npc: 'data/retention/characters/npc',
  companion: 'data/retention/characters/companion',
  stickers: 'data/retention/characters/stickers',
  icons: 'data/retention/cosmetics/icons',
  skins: 'data/retention/cosmetics/skins',
  decoration: 'data/retention/cosmetics/decoration',
  themes: 'data/retention/cosmetics/themes',
  scenes: 'data/retention/scenes',
};
const out = join(root, 'lib/retention/art');
mkdirSync(out, { recursive: true });
const OPEN = /^<svg [^>]*aria-label="([^"]*)"[^>]*>\n?/;
const total = {};
for (const [name, dir] of Object.entries(groups)) {
  const files = readdirSync(join(root, dir)).filter(f => f.endsWith('.svg')).sort();
  const map = {};
  for (const f of files) {
    const src = readFileSync(join(root, dir, f), 'utf8').replace(/\r\n/g, '\n');
    const m = OPEN.exec(src);
    if (!m || !src.trimEnd().endsWith('</svg>')) throw new Error(`${dir}/${f}: unexpected svg wrapper`);
    map[f.slice(0, -4)] = { l: m[1], b: src.slice(m[0].length).replace(/<\/svg>\s*$/, '').trim() };
  }
  total[name] = files.length;
  const body = `// GENERATED by tools/retention/build-art.mjs from ${dir}/*.svg — edit the .svg sources, not this file.\n` +
    `export const ART: Readonly<Record<string, { l: string; b: string }>> = ${JSON.stringify(map)};\n`;
  writeFileSync(join(out, `${name}.generated.ts`), body);
}
console.log('retention art bundled:', JSON.stringify(total));
