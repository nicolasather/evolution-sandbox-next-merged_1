/** Deterministic bot sweep: `npx tsx tools/swarm/balance.ts [--md docs/swarm-survival/BALANCE_REPORT.md] [--quick]`.
 *  Reports clear rate, waves completed, beacon health and spending per team size / role mix / accuracy / session length.
 *  Bots are deliberately simple (kite, orbit the beacon, use abilities when enemies are close): the numbers are a floor for human play, not a promise. */
import { writeFileSync } from 'node:fs';
import { drive, mkRoom } from '../../lib/swarm/testkit';
import type { Role } from '../../lib/swarm/domain';

const quick = process.argv.includes('--quick'); const mdIdx = process.argv.indexOf('--md');
const sizes = quick ? [1, 5] : [1, 3, 5]; const minutes = quick ? [5, 15] : [5, 15, 45]; const accs = quick ? [0.6, 1] : [0.35, 0.6, 0.85, 1]; const seeds = quick ? [1] : [1, 2, 3];
const mixes: (Role | 'mix')[] = quick ? ['mix', 'guardian'] : ['mix', 'guardian', 'striker', 'medic', 'engineer', 'scout'];
type Row = { size: number; min: number; acc: number; mix: string; clear: number; waves: number; beacon: number; spent: number; runs: number };
const rows: Row[] = [];
const t0 = Date.now();
for (const size of sizes) for (const min of minutes) for (const acc of accs) for (const mix of mixes) {
  if (min === 45 && (size !== 3 || mix !== 'mix')) continue; // 45-minute runs: one representative team
  let clear = 0, waves = 0, beacon = 0, spent = 0, n = 0;
  for (const seed of seeds) {
    const fx = mkRoom({ sizes: [size], minutes: min, roles: [mix], seed, pool: 60 });
    const { room } = drive(fx, { accuracy: acc });
    const s = room.results!.standings[0]!; clear += room.results!.outcome === 'won' ? 1 : 0; waves += s.wavesCompleted / room.plan.waves.length; beacon += s.beaconPct; spent += s.spent; n++;
  }
  rows.push({ size, min, acc, mix, clear: clear / n, waves: waves / n, beacon: beacon / n, spent: spent / n, runs: n });
}
const pct = (x: number) => `${Math.round(x * 100)}%`;
const lines = ['| players | min | accuracy | roles | clear | waves done | beacon HP | spent pts |', '|---:|---:|---:|---|---:|---:|---:|---:|', ...rows.map((r) => `| ${r.size} | ${r.min} | ${pct(r.acc)} | ${r.mix} | ${pct(r.clear)} | ${pct(r.waves)} | ${Math.round(r.beacon)}% | ${Math.round(r.spent)} |`)];
const md = `# Balance report (bot sweep)\n\nGenerated by \`tools/swarm/balance.ts\` (${rows.length} cells, ${seeds.length} seed(s) each, ${Math.round((Date.now() - t0) / 1000)} s). Bots kite and use abilities but never aim or plan, so human teams should do at least this well.\n\n${lines.join('\n')}\n`;
if (mdIdx > 0) writeFileSync(process.argv[mdIdx + 1]!, md); else console.log(md);
