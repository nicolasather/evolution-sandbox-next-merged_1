/** Role marginal-contribution sweep: `npx tsx tools/swarm/roles.ts [--md docs/swarm-survival/ROLE_REPORT.md] [--quick]`.
 *  Takes one five-player team, swaps ONE role for a Striker (the strongest damage role) and measures what the team loses under pressure
 *  (challenge difficulty, 60% answer accuracy). Non-dominance means: a mixed team survives better than five Strikers, and removing any support role costs the team something. */
import { writeFileSync } from 'node:fs';
import { drive, mkRoom } from '../../lib/swarm/testkit';
import type { Role } from '../../lib/swarm/domain';

export const COMPOSITIONS: Record<string, Role[]> = {
  'one of each role': ['guardian', 'striker', 'medic', 'engineer', 'scout'],
  'five Strikers': ['striker', 'striker', 'striker', 'striker', 'striker'],
  'no Medic (Striker instead)': ['guardian', 'striker', 'striker', 'engineer', 'scout'],
  'no Guardian (Striker instead)': ['striker', 'striker', 'medic', 'engineer', 'scout'],
  'no Engineer (Striker instead)': ['guardian', 'striker', 'medic', 'striker', 'scout'],
  'no Scout (Striker instead)': ['guardian', 'striker', 'medic', 'engineer', 'striker'],
  'five Medics': ['medic', 'medic', 'medic', 'medic', 'medic'],
  'five Guardians': ['guardian', 'guardian', 'guardian', 'guardian', 'guardian'],
};
export type CompStat = { clear: number; waves: number; beacon: number; downs: number; damage: number; runs: number };
export function sweep(o: { seeds?: number; minutes?: number; accuracy?: number; difficulty?: 'easy' | 'normal' | 'challenge'; only?: string[] } = {}): Record<string, CompStat> {
  const out: Record<string, CompStat> = {}; const seeds = o.seeds ?? 10;
  for (const [name, roles] of Object.entries(COMPOSITIONS)) {
    if (o.only && !o.only.includes(name)) continue; let clear = 0, waves = 0, beacon = 0, downs = 0, damage = 0;
    for (let s = 1; s <= seeds; s++) {
      const fx = mkRoom({ sizes: [5], minutes: o.minutes ?? 15, seed: 300 + s, pool: 60, roleList: [roles], config: { difficulty: o.difficulty ?? 'challenge' } });
      const { room } = drive(fx, { accuracy: o.accuracy ?? 0.6 }); const st = room.results!.standings[0]!; const a = room.arenas.t1!;
      clear += room.results!.outcome === 'won' ? 1 : 0; waves += st.wavesCompleted / room.plan.waves.length; beacon += st.beaconPct;
      for (const p of Object.values(a.players)) { downs += p.downs; damage += p.damageDealt; }
    }
    out[name] = { clear: clear / seeds, waves: waves / seeds, beacon: beacon / seeds, downs: downs / seeds, damage: damage / seeds, runs: seeds };
  }
  return out;
}
if (require.main === module) {
  const st = sweep({ seeds: process.argv.includes('--quick') ? 4 : 10 }); const pct = (x: number) => `${Math.round(x * 100)}%`;
  const rows = Object.entries(st).map(([n, r]) => `| ${n} | ${pct(r.clear)} | ${pct(r.waves)} | ${Math.round(r.beacon)}% | ${r.downs.toFixed(1)} | ${Math.round(r.damage)} | ${r.runs} |`);
  const md = `# Role marginal-contribution report\n\nGenerated by \`tools/swarm/roles.ts\`. Five-player teams, 15-minute matches, **challenge** difficulty, bots at 60% answer accuracy, fixed seeds. Each row swaps one role for a Striker or fills the team with one role.\n\n| team | cleared | waves done | beacon HP at end | player downs | damage dealt | runs |\n|---|---:|---:|---:|---:|---:|---:|\n${rows.join('\n')}\n\nBots kite and use abilities but do not aim, so this shows what the role kits contribute mechanically, not how humans play.\n`;
  const i = process.argv.indexOf('--md'); if (i > 0) writeFileSync(process.argv[i + 1]!, md); else console.log(md);
}
